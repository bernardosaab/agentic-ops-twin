"""Harness evaluation: golden jobs and negative tests for the governed write path.

This evaluates the *harness*, not a model. The question is whether the system of record ends up
matching exactly what named approvers signed, and whether every unauthorised or stale attempt
leaves it unchanged. Each case runs in a fresh, isolated workspace (ledger, sandboxed system of
record and keyring). A refusal counts as passing only if the system of record is byte-for-byte
unchanged.
"""

from __future__ import annotations

import tempfile
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict

from agentic_ops_twin.agent.router import Router
from agentic_ops_twin.decision.study import evaluate_change_set
from agentic_ops_twin.governance.brief import build_brief
from agentic_ops_twin.governance.ledger import Ledger
from agentic_ops_twin.governance.trust import TrustAssessment, assess
from agentic_ops_twin.governance.writegate import (
    Keyring,
    SystemOfRecord,
    approve,
    release,
    stage,
)
from agentic_ops_twin.packs import get_pack
from agentic_ops_twin.packs.base import DomainPack
from agentic_ops_twin.research.calibrate import calibrate
from agentic_ops_twin.simulation.engine import simulate
from agentic_ops_twin.simulation.exogenous import arrival_stream

MAKER = "ops-analyst"
APPROVERS = ("approver-a", "approver-b")


class CaseResult(BaseModel):
    model_config = ConfigDict(extra="forbid")
    id: str
    kind: str
    description: str
    expected: str
    actual: str
    system_of_record_unchanged: bool | None
    reasons: list[str]
    passed: bool


class HarnessReport(BaseModel):
    model_config = ConfigDict(extra="forbid")
    pack_id: str
    cases: list[CaseResult]
    passed: int
    total: int
    reconstruction_pack_records: int
    reconstruction_chain_verified: bool


@dataclass
class Workspace:
    root: Path
    ledger: Ledger
    sor: SystemOfRecord
    keyring: Keyring


def _workspace(root: Path) -> Workspace:
    ws = Workspace(
        root,
        Ledger(root / "ledger.sqlite"),
        SystemOfRecord(root / "sor.json"),
        Keyring(root / "keyring.json"),
    )
    for name in (*APPROVERS, MAKER):
        ws.keyring.add(name)
    return ws


def _history_trust(pack: DomainPack, *, mechanisms: bool) -> TrustAssessment:
    hours = 960.0
    model = pack.model.model_copy(update={"horizon_hours": hours, "warmup_hours": 0.0})
    demand = pack.condition("normal")
    kw: dict[str, Any] = {}
    if mechanisms:
        demand = demand.model_copy(update={"hourly_profile": pack.hidden_truth.hourly_profile})
        kw["mechanisms"] = pack.hidden_truth.mechanisms
    run = simulate(model, 500, demand, record_log=True, **kw)
    arrivals = arrival_stream(model, 500, demand)
    assert run.event_log is not None
    if not mechanisms:
        # Sanity: a history generated by the twin's own assumptions should calibrate cleanly.
        calibrate(pack.model, arrivals, run.event_log, hours, diagnostics=False)
    return assess(
        pack.model,
        arrivals=arrivals,
        events=run.event_log,
        history_hours=hours,
        evidence=(
            "hidden-truth history (960 h)"
            if mechanisms
            else "history generated under the twin's own assumptions (960 h)"
        ),
    )


class _Fixture:
    """Shared, deterministic inputs: one validated proposal, its experiment and brief."""

    def __init__(self, pack: DomainPack, request: str) -> None:
        self.pack = pack
        routed = Router().route(request, pack)
        assert routed.outcome is not None and routed.outcome.change_set is not None
        assert routed.outcome.demand_condition is not None
        self.routed = routed
        self.change_set = routed.outcome.change_set
        self.base_row, self.alt_row = evaluate_change_set(
            pack, self.change_set, routed.outcome.demand_condition, profile="quick", workers=1
        )
        self.trust = {
            "unvalidated": assess(pack.model),
            "validated": _history_trust(pack, mechanisms=False),
            "inadequate": _history_trust(pack, mechanisms=True),
        }

    def seed(self, ws: Workspace, trust: str) -> tuple[str, str]:
        req = ws.ledger.append("request", {"pack": self.pack.id, "text": self.routed.request})
        prop = ws.ledger.append(
            "proposal", self.routed.model_dump(mode="json"), refs=[req.record_id]
        )
        exp = ws.ledger.append(
            "experiment",
            {
                "type": "proposal_experiment",
                "baseline": self.base_row.model_dump(mode="json"),
                "alternative": self.alt_row.model_dump(mode="json"),
            },
            edges=[("evaluates", prop.record_id)],
        )
        brief = build_brief(
            pack_id=self.pack.id,
            subject=self.change_set.label(),
            source_record=exp.record_id,
            model=self.pack.model,
            rows=[self.alt_row],
            baseline_rows=[self.base_row],
            change_set=self.change_set,
        )
        brec = ws.ledger.append(
            "brief", {"brief": brief.model_dump(mode="json")}, refs=[exp.record_id]
        )
        trec = ws.ledger.append("trust_assessment", self.trust[trust].model_dump(mode="json"))
        return brec.record_id, trec.record_id


Scenario = Callable[[Workspace, str, str], tuple[str, list[str]]]


def _stage(ws: Workspace, pack: DomainPack, brief: str, trust: str) -> str:
    return stage(
        ws.ledger, ws.sor, pack, brief_record=brief, trust_record=trust, maker=MAKER
    ).record_id


def run_harness_eval(
    pack_id: str = "insurance",
    request: str = "Automate triage under normal demand.",
    export_dir: Path | None = None,
) -> HarnessReport:
    pack = get_pack(pack_id)
    fx = _Fixture(pack, request)
    results: list[CaseResult] = []
    recon_records, recon_ok = 0, False

    def case(
        cid: str,
        kind: str,
        desc: str,
        expected: str,
        trust: str,
        body: Callable[[Workspace, str, str], tuple[str, list[str]]],
        *,
        self_measured: bool = False,
    ) -> None:
        """``self_measured``: the scenario changes the system of record on purpose before the
        refused attempt, so the body itself compares state immediately around that attempt."""
        nonlocal recon_records, recon_ok
        with tempfile.TemporaryDirectory() as tmp:
            ws = _workspace(Path(tmp))
            brief, trec = fx.seed(ws, trust)
            before = ws.sor.read(pack)
            actual, reasons = body(ws, brief, trec)
            after = ws.sor.read(pack)
            unchanged = (actual != "changed") if self_measured else before == after
            if cid == "G1" and actual == "release":
                rel = ws.ledger.records("release")[-1]
                pack_ = ws.ledger.reconstruction_pack(rel.record_id)
                recon_records, recon_ok = len(pack_.records), pack_.chain_verified
                if export_dir is not None:
                    import json as _json

                    export_dir.mkdir(parents=True, exist_ok=True)
                    (export_dir / "golden-release-reconstruction.json").write_text(
                        _json.dumps(pack_.to_json(), indent=1), encoding="utf-8"
                    )
                    (export_dir / "golden-release-reconstruction.md").write_text(
                        pack_.timeline_markdown(), encoding="utf-8"
                    )
            passed = actual == expected and (unchanged if expected == "refusal" else True)
            results.append(
                CaseResult(
                    id=cid,
                    kind=kind,
                    description=desc,
                    expected=expected,
                    actual=actual,
                    system_of_record_unchanged=unchanged,
                    reasons=reasons,
                    passed=passed,
                )
            )
            ws.ledger.close()

    def released(ws: Workspace, pkg: str) -> tuple[str, list[str]]:
        rec = release(ws.ledger, ws.sor, ws.keyring, pack, package_record=pkg, requester=MAKER)
        if rec.kind == "release":
            expected = ws.ledger.get(pkg)
            assert expected is not None
            ok = ws.sor.read(pack) == expected.payload["package"]["after"]
            return ("release" if ok else "release-mismatch"), []
        return "refusal", list(rec.payload["reasons"])

    def approve_all(ws: Workspace, pkg: str, ack: bool = True) -> None:
        for a in APPROVERS:
            approve(
                ws.ledger, ws.keyring, package_record=pkg, reviewer=a, acknowledge_unvalidated=ack
            )

    # --- golden jobs ---------------------------------------------------------------------------
    def g1(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve_all(ws, pkg)
        return released(ws, pkg)

    case(
        "G1",
        "golden",
        "High-risk change (automation, unvalidated twin), two acknowledging "
        "approvers: written and read back",
        "release",
        "unvalidated",
        g1,
    )

    def g2(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve_all(ws, pkg)
        return released(ws, pkg)

    case(
        "G2",
        "golden",
        "Same change with a validated twin: still high-risk (automation "
        "switch); two approvers release it",
        "release",
        "validated",
        g2,
    )

    # --- negative tests ------------------------------------------------------------------------
    def n_no_approval(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        return released(ws, _stage(ws, pack, brief, trust))

    case("N1", "negative", "No approval at all", "refusal", "unvalidated", n_no_approval)

    def n_one(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve(
            ws.ledger,
            ws.keyring,
            package_record=pkg,
            reviewer=APPROVERS[0],
            acknowledge_unvalidated=True,
        )
        return released(ws, pkg)

    case(
        "N2",
        "negative",
        "High-risk package with a single approval",
        "refusal",
        "unvalidated",
        n_one,
    )

    def n_self(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve(
            ws.ledger, ws.keyring, package_record=pkg, reviewer=MAKER, acknowledge_unvalidated=True
        )
        approve(
            ws.ledger,
            ws.keyring,
            package_record=pkg,
            reviewer=APPROVERS[0],
            acknowledge_unvalidated=True,
        )
        return released(ws, pkg)

    case(
        "N3",
        "negative",
        "Maker approves their own package (maker-checker)",
        "refusal",
        "unvalidated",
        n_self,
    )

    def n_forged(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        rec = ws.ledger.get(pkg)
        assert rec is not None
        for a in APPROVERS:
            ws.ledger.append(
                "approval",
                {
                    "package": pkg,
                    "payload_sha256": rec.payload["payload_sha256"],
                    "reviewer": a,
                    "decision": "approve",
                    "expires_at": (datetime.now(UTC) + timedelta(hours=1)).isoformat(
                        timespec="seconds"
                    ),
                    "token": "0" * 64,
                    "acknowledged_unvalidated": True,
                    "note": "forged",
                    "identity": "forged",
                },
                edges=[("approves", pkg)],
            )
        return released(ws, pkg)

    case("N4", "negative", "Approvals with forged tokens", "refusal", "unvalidated", n_forged)

    def n_expired(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        for a in APPROVERS:
            approve(
                ws.ledger,
                ws.keyring,
                package_record=pkg,
                reviewer=a,
                acknowledge_unvalidated=True,
                issued_at=datetime.now(UTC) - timedelta(days=3),
            )
        return released(ws, pkg)

    case("N5", "negative", "Approval tokens expired", "refusal", "unvalidated", n_expired)

    def n_ack(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve_all(ws, pkg, ack=False)
        return released(ws, pkg)

    case(
        "N6",
        "negative",
        "Unvalidated twin, approvers did not acknowledge it",
        "refusal",
        "unvalidated",
        n_ack,
    )

    def n_inadequate(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve_all(ws, pkg)
        return released(ws, pkg)

    case(
        "N7",
        "negative",
        "Trust gate: history shows mechanisms the twin omits",
        "refusal",
        "inadequate",
        n_inadequate,
    )

    def n_stale_brief(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve_all(ws, pkg)
        ws.ledger.invalidate(brief, "evidence superseded")
        return released(ws, pkg)

    case(
        "N8",
        "negative",
        "Source brief invalidated after approval",
        "refusal",
        "unvalidated",
        n_stale_brief,
    )

    def n_drift(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve_all(ws, pkg)
        cfg = ws.sor.read(pack)
        cfg["capacities"]["adjuster"] += 1
        ws.sor.write(pack.id, cfg)
        before = ws.sor.read(pack)
        outcome, reasons = released(ws, pkg)
        return (outcome if ws.sor.read(pack) == before else "changed"), reasons

    case(
        "N9",
        "negative",
        "System of record changed after the quote (stale before-state)",
        "refusal",
        "unvalidated",
        n_drift,
        self_measured=True,
    )

    def n_reject(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve(
            ws.ledger,
            ws.keyring,
            package_record=pkg,
            reviewer=APPROVERS[0],
            acknowledge_unvalidated=True,
        )
        approve(ws.ledger, ws.keyring, package_record=pkg, reviewer=APPROVERS[1], decision="reject")
        return released(ws, pkg)

    case("N10", "negative", "One approver rejects", "refusal", "unvalidated", n_reject)

    def n_twice(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        pkg = _stage(ws, pack, brief, trust)
        approve_all(ws, pkg)
        first, _ = released(ws, pkg)
        assert first == "release"
        before = ws.sor.read(pack)
        outcome, reasons = released(ws, pkg)
        return (outcome if ws.sor.read(pack) == before else "changed"), reasons

    case(
        "N11",
        "negative",
        "Replaying an already-released package",
        "refusal",
        "unvalidated",
        n_twice,
        self_measured=True,
    )

    def n_control(ws: Workspace, brief: str, trust: str) -> tuple[str, list[str]]:
        out = Router().route("Skip the fraud check under normal demand.", pack)
        if out.outcome is not None and out.outcome.change_set is not None:
            return "runnable", []
        return "refusal", [i.code for i in (out.outcome.issues if out.outcome else [])]

    case(
        "N12",
        "negative",
        "Request to remove a mandatory control never becomes a change set",
        "refusal",
        "unvalidated",
        n_control,
    )

    passed = sum(c.passed for c in results)
    return HarnessReport(
        pack_id=pack_id,
        cases=results,
        passed=passed,
        total=len(results),
        reconstruction_pack_records=recon_records,
        reconstruction_chain_verified=recon_ok,
    )


def render_harness(rep: HarnessReport) -> str:
    lines = [
        f"# Harness evaluation: governed write path ({rep.pack_id})",
        "",
        f"**{rep.passed}/{rep.total} cases passed.** A refusal passes only if the sandboxed "
        "system of record is unchanged. This evaluates the harness, not a model: the proposer "
        "is the compiled rule path.",
        "",
        f"The reconstruction pack for the golden release links {rep.reconstruction_pack_records} "
        f"records, and its hash chain is "
        f"{'verified' if rep.reconstruction_chain_verified else 'NOT verified'}.",
        "",
        "| Case | Type | Scenario | Expected | Actual | System of record unchanged | Pass |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in rep.cases:
        unchanged = (
            "—"
            if c.expected == "release"
            else ("yes" if c.system_of_record_unchanged else "**no**")
        )
        lines.append(
            f"| {c.id} | {c.kind} | {c.description} | {c.expected} | {c.actual} | "
            f"{unchanged} | {'✅' if c.passed else '❌'} |"
        )
    lines += ["", "## Refusal reasons recorded", ""]
    for c in rep.cases:
        if c.reasons:
            lines.append(f"- **{c.id}**: " + "; ".join(c.reasons))
    return "\n".join(lines) + "\n"
